pub const CELL: usize = 8;
pub const ATLAS: usize = 128;
pub const SOLID: usize = 0x5f;

pub fn index(c: char) -> usize {
    match c as u32 {
        v @ 0x20..=0x7e => (v - 0x20) as usize,
        v @ 0xa0..=0xff => (v - 0xa0 + 96) as usize,
        _ => ('?' as u32 - 0x20) as usize,
    }
}

pub fn cell(i: usize) -> [usize; 2] {
    [(i % 16) * CELL, (i / 16) * CELL]
}

pub fn atlas() -> Vec<u8> {
    (0..ATLAS * ATLAS)
        .map(|p| {
            let (x, y) = (p % ATLAS, p / ATLAS);
            let g = (y / CELL) * 16 + x / CELL;
            let bit = GLYPHS.get(g).map_or(0, |v| v >> ((y % CELL) * 8) >> (7 - x % CELL) & 1);
            (bit * 255) as u8
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn portuguese_glyphs_are_distinct() {
        let set = "aãáàâçeéêiíoóôõuúAÃÁÇÉÊÍÓÔÕÚ";
        let g: Vec<u64> = set.chars().map(|c| GLYPHS[index(c)]).collect();
        assert!(g.iter().all(|v| *v != 0));
        assert!(g.iter().enumerate().all(|(i, a)| g[i + 1..].iter().all(|b| a != b)));
        assert_eq!(GLYPHS[SOLID], u64::MAX);
    }

    #[test]
    fn atlas_matches_table() {
        let a = atlas();
        let [x, y] = cell(index('A'));
        let row = |r: usize| (0..8).fold(0u64, |acc, b| acc << 1 | (a[(y + r) * ATLAS + x + b] != 0) as u64);
        assert!((0..8).all(|r| row(r) == GLYPHS[index('A')] >> (r * 8) & 0xff));
    }
}
